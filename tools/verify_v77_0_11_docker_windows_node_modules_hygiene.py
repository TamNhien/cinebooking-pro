from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
checks = []

def text(rel):
    return (ROOT / rel).read_text(encoding='utf-8')

def ok(cond, msg):
    checks.append(bool(cond))
    print(f"[ {'OK' if cond else 'FAIL'} ] {msg}")

ignore = text('frontend/.dockerignore')
dockerfile = text('frontend/Dockerfile')
readme = text('README.md')
ci = text('.github/workflows/ci.yml')
release = text('scripts/release.ps1')
diagnose = text('tools/diagnose-v77.ps1')
makefile = text('Makefile')
old = text('tools/verify_v77_0_10_vietnamese_localizer_immutable_ledger.py')

ignored = {line.strip().rstrip('/') for line in ignore.splitlines() if line.strip() and not line.lstrip().startswith('#')}
for item in ['node_modules', '.next', 'playwright-report', 'test-results', 'blob-report', '.playwright', 'coverage', 'out', 'dist']:
    ok(item in ignored, f'Frontend Docker context ignores generated/host artifact {item}/')

ok('.env' in ignored and '.env.*' in ignored, 'Frontend Docker context excludes local environment-secret files')
ok('!.env.example' in ignore, 'Frontend Docker context keeps the safe env example available')
ok('COPY package*.json ./' in dockerfile, 'Frontend dependency stage copies available npm manifests without requiring an omitted lockfile')
ok('RUN npm install' in dockerfile, 'Frontend Docker dependency stage installs dependencies inside Linux')
ok('COPY --from=deps /app/node_modules ./node_modules' in dockerfile, 'Frontend build stage consumes Linux-installed dependencies from deps stage')
ok('COPY . .' in dockerfile, 'Frontend build stage still copies application source')
ok(dockerfile.index('COPY --from=deps /app/node_modules ./node_modules') < dockerfile.index('COPY . .'), 'Linux node_modules is installed before source copy and protected by .dockerignore')
ok('COPY node_modules' not in dockerfile, 'Dockerfile never copies host node_modules directly')
ok('node.exe' not in dockerfile, 'Dockerfile has no Windows node executable dependency')
ok('V77.0.11' in readme and 'Docker' in readme, 'README documents V77.0.11 Docker Windows dependency hygiene')
ok('verify_v77_0_11_docker_windows_node_modules_hygiene.py' in ci, 'CI runs V77.0.11 Docker hygiene verifier')
ok('verify_v77_0_11_docker_windows_node_modules_hygiene.py' in release, 'Stable release preflight runs V77.0.11 verifier')
ok('verify_v77_0_11_docker_windows_node_modules_hygiene.py' in diagnose, 'V77 diagnostics chain V77.0.11 verifier')
ok('verify-v77-docker-windows-hygiene' in makefile, 'Makefile exposes V77.0.11 verification target')
ok('v77.0.11' in makefile, 'Makefile latest V77 patch target is v77.0.11')
ok('V77.0.10' in old, 'Historical V77.0.10 verifier remains present and immutable in scope')
ok('V72' in readme and '67 public tables' in readme, 'V77.0.11 remains no-schema on Flyway V72 / 67 public tables')

passed=sum(checks)
print(f"\nV77.0.11 Docker Windows node_modules hygiene verification: {passed}/{len(checks)} checks passed")
raise SystemExit(0 if all(checks) else 1)
